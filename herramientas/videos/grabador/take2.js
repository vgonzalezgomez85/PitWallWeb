const { Rec, sleep } = require('./rec');
const TAG = `document.querySelectorAll('.td-card').forEach((c, ti) => { c.querySelectorAll('.td-lane--drag').forEach((e, i) => e.setAttribute('data-rec', 't' + ti + '-' + i)); c.querySelectorAll('button').forEach(b => { if (/azar/i.test(b.textContent)) b.setAttribute('data-rec', 't' + ti + '-azar'); }); })`;
(async () => {
  const r = new Rec(__dirname + '/take2');
  await r.start();
  await r.go('http://localhost:3300/');
  await r.click({ text: 'Esta ventana' });
  await r.go('http://localhost:3300/');
  await r.move(1200, 700, 1);
  await r.recStart();
  r.mark('inicio'); await sleep(1500);
  await r.click({ text: 'Carrera sprint', sel: 'a' }, { pause: 500 }); await r.waitNav();
  r.mark('asistente'); await sleep(1800);
  await r.click('input[name=name]'); await r.type('Copa de Navidad'); await sleep(900);
  r.mark('crear'); await r.click('#nrCta', { pause: 600 }); await r.waitNav();
  r.mark('tandas'); await r.move(960, 600); await sleep(3500);
  r.mark('arrastrar'); await r.eval(TAG);
  await r.drag({ text: 'Laura Vidal', sel: '.td-pil' }, '[data-rec="t0-0"]'); await sleep(700); await r.eval(TAG);
  await r.drag({ text: 'Marta Soler', sel: '.td-pil' }, '[data-rec="t0-1"]'); await sleep(1000); await r.eval(TAG);
  r.mark('tocar'); await r.click({ text: 'Anna Gil', sel: '.td-pil' }, { pause: 400 }); await sleep(1300); await r.eval(TAG);
  await r.click('[data-rec="t0-2"]', { pause: 400 }); await sleep(900); await r.eval(TAG);
  await r.click({ text: 'Jordi Puig', sel: '.td-pil' }, { pause: 300 }); await sleep(800); await r.eval(TAG);
  await r.click('[data-rec="t0-3"]', { pause: 300 }); await sleep(1300);
  r.mark('anadir_tanda'); await r.click('.td-addtile', { pause: 500 }); await sleep(1600); await r.eval(TAG);
  r.mark('azar'); await r.click('[data-rec="t1-azar"]', { pause: 600 }); await sleep(2800);
  await r.move(1000, 560); await sleep(1500);
  r.mark('preview'); await r.click('#tdPreviewBtn', { pause: 500 }); await sleep(1200);
  await r.scrollToEl('#tdPreview', 110, 1500); await r.move(960, 520); await sleep(5000);
  r.mark('crear_tandas'); await r.click('#tdSubmit', { pause: 600 }); await r.waitNav();
  r.mark('carrera'); await sleep(600); await r.move(1760, 820, 30); await sleep(3500);
  await r.recStop(__dirname + '/take2.mp4');
  console.log(await r.eval('location.href'));
  await r.close();
})().catch(e => { console.error(e); process.exit(1); });
